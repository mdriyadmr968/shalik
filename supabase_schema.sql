-- 1. EXTENSIONS
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- ==============================================================================
-- 2. TABLES
-- ==============================================================================

-- Table: farmer_profiles
-- Stores farmer onboarding information, location, crops, and language preference
CREATE TABLE IF NOT EXISTS farmer_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id BIGINT UNIQUE,
    farmer_name TEXT NOT NULL,
    district TEXT,
    upazila TEXT,
    primary_crops TEXT,
    preferred_language VARCHAR(10) DEFAULT 'bn',
    is_onboarded BOOLEAN DEFAULT true,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: chat_conversations
-- Groups chat interactions into threads
CREATE TABLE IF NOT EXISTS chat_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id BIGINT UNIQUE,
    title TEXT NOT NULL,
    last_message_preview TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: chat_messages
-- Stores bilingual advisory dialog, questions, and multimodal citations
CREATE TABLE IF NOT EXISTS chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    local_id BIGINT UNIQUE,
    conversation_id BIGINT NOT NULL,
    sender VARCHAR(10) NOT NULL CHECK (sender IN ('USER', 'SHALIK')),
    text TEXT NOT NULL,
    timestamp TIMESTAMPTZ DEFAULT NOW(),
    image_uri TEXT,
    cited_sources TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: alerts
-- Real-time disaster, meteorological, and agro-climatic early warnings
CREATE TABLE IF NOT EXISTS alerts (
    id TEXT PRIMARY KEY,
    type VARCHAR(50) NOT NULL,
    severity_level INT NOT NULL DEFAULT 1,
    district_codes TEXT,
    upazila_codes TEXT,
    valid_from TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    valid_to TIMESTAMPTZ NOT NULL DEFAULT (NOW() + INTERVAL '3 days'),
    message_bn TEXT NOT NULL,
    message_en TEXT,
    source TEXT NOT NULL,
    action_templates TEXT,
    signature TEXT,
    received_at TIMESTAMPTZ DEFAULT NOW()
);

-- Table: telemetry_logs
-- Performance tracking for on-device TTFT (Time To First Token) and latency
CREATE TABLE IF NOT EXISTS telemetry_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id TEXT,
    event_name VARCHAR(100) NOT NULL,
    ttft_ms INT,
    latency_ms INT,
    tokens_generated INT,
    model_name VARCHAR(100),
    device_info JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- ==============================================================================
-- 3. INDEXES FOR HIGH QUERY PERFORMANCE
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_chat_messages_conversation ON chat_messages(conversation_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_local_id ON chat_messages(local_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_timestamp ON chat_messages(timestamp DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_received_at ON alerts(received_at DESC);
CREATE INDEX IF NOT EXISTS idx_alerts_valid_window ON alerts(valid_from, valid_to);
CREATE INDEX IF NOT EXISTS idx_farmer_profiles_district ON farmer_profiles(district);

